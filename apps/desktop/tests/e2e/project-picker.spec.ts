import { test, expect, _electron as electron } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { startFixture, TEST_PASSWORD } from '../fixtures';

test('project picker scrolls, keeps selection and keyboard focus inside the dialog', async ({}, testInfo) => {
  const fixture = await startFixture();
  for (let index = 0; index < 30; index++) fixture.projects.push({ id: `extra-${index}`, name: `项目 ${String(index).padStart(2, '0')}`, path: `/srv/projects/project-${index}`, createdAt: new Date().toISOString() });
  const dir = await mkdtemp(join(tmpdir(), 'remote-pi-dialog-'));
  const env: Record<string, string> = { ...Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined)), REMOTE_PI_TEST_MODE: '1', REMOTE_PI_USER_DATA: dir, REMOTE_PI_TEST_KNOWN_HOSTS: join(dir, 'known_hosts') };
  delete env.ELECTRON_RUN_AS_NODE;
  const desktop = await electron.launch({ args: ['.'], env });
  try {
    const page = await desktop.firstWindow();
    const shortcut = process.platform === 'darwin' ? 'Meta+n' : 'Control+n';
    await page.getByLabel('服务器地址', { exact: true }).fill('127.0.0.1');
    await page.getByText('端口与私钥设置', { exact: false }).click();
    await page.getByLabel('SSH 端口', { exact: true }).fill(String(fixture.sshPort));
    await page.getByLabel('远端 Pi Web 端口', { exact: true }).fill(String(fixture.webPort));
    await page.getByRole('button', { name: '连接工作台', exact: true }).click();
    await page.getByRole('button', { name: '信任并连接', exact: true }).click();
    await page.getByLabel('SSH 验证响应').fill(TEST_PASSWORD);
    await page.getByRole('button', { name: '继续连接', exact: true }).click();
    const input = page.getByLabel('发送消息', { exact: true });
    await expect(input).toBeEnabled();
    await input.press(shortcut);
    const dialog = page.getByRole('dialog', { name: '新建对话', exact: true });
    const picker = dialog.getByRole('combobox', { name: '选择项目', exact: true });
    await expect(picker).toBeFocused();
    await picker.click();
    const list = dialog.getByRole('listbox', { name: '选择项目', exact: true });
    await expect(list).toBeVisible();
    await list.hover(); await page.mouse.wheel(0, 1200);
    await expect.poll(() => list.evaluate((node) => node.scrollTop)).toBeGreaterThan(0);
    await expect(dialog.getByRole('button', { name: '创建对话', exact: true })).toBeInViewport();
    await picker.press('Escape');
    await expect(list).toHaveCount(0); await expect(dialog).toBeVisible();
    await picker.press('ArrowDown'); await picker.press('End');
    await expect(list.getByRole('option', { name: /项目 29/ })).toBeInViewport();
    await page.screenshot({ path: testInfo.outputPath('project-picker-light.png'), animations: 'disabled' });
    await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
    await page.screenshot({ path: testInfo.outputPath('project-picker-dark.png'), animations: 'disabled' });
    await picker.press('Enter');
    await expect(picker).toContainText('项目 29');
    await expect(dialog.getByRole('combobox', { name: '选择工作区' })).toContainText('/srv/projects/project-29');
    await dialog.getByRole('button', { name: '创建对话', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    expect(fixture.calls.findLast((call) => call.method === 'POST' && call.path.endsWith('/sessions'))?.body.cwd).toBe('/srv/projects/project-29');
    fixture.directorySuggestions.splice(0, fixture.directorySuggestions.length, ...Array.from({ length: 30 }, (_, index) => ({ path: `/srv/projects/directory-${String(index).padStart(2, '0')}`, kind: 'directory' })));
    await page.getByLabel('添加项目', { exact: true }).click();
    const add = page.getByRole('dialog', { name: '添加远端项目', exact: true });
    const directory = add.getByRole('combobox', { name: '远端目录', exact: true });
    await directory.fill('/srv/projects/');
    const suggestions = add.getByRole('listbox', { name: '远端目录', exact: true });
    await expect(suggestions.getByRole('option')).toHaveCount(30);
    await suggestions.hover(); await page.mouse.wheel(0, 1600);
    await expect.poll(() => suggestions.evaluate((node) => node.scrollTop)).toBeGreaterThan(0);
    await page.screenshot({ path: testInfo.outputPath('directory-picker.png'), animations: 'disabled' });
    await suggestions.getByRole('option', { name: /directory-29/ }).click();
    await expect(directory).toHaveValue('/srv/projects/directory-29');
    await expect(suggestions).toHaveCount(0);
    expect(fixture.calls.filter((call) => call.method === 'POST' && call.path.endsWith('/projects'))).toHaveLength(0);
    await directory.fill('/manual/custom');
    await expect(directory).toHaveValue('/manual/custom');
    await add.getByRole('button', { name: '取消', exact: true }).click();
  } finally { await desktop.close(); await fixture.close(); await rm(dir, { recursive: true, force: true }); }
});
